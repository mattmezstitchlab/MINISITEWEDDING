/** La direction d'un numéro (1 à 54). Le rang, jamais le numéro, sert d'index. */
export function directionDuNumero(numero: number): DirectionDuMagazine {
  return DIRECTIONS[numero - 1] ?? DIRECTIONS[0]!;
}

/** Vrai quand les 54 directions sont écrites, dans l'ordre, sans trou. */
export const DIRECTIONS_COMPLETES =
  DIRECTIONS.length === 54 && DIRECTIONS.every((d, i) => d.numero === i + 1);
