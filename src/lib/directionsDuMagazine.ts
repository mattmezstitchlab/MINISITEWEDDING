/**
 * LA DIRECTION ARTISTIQUE DES 54 MAGAZINES
 *
 * Cinquante-quatre fois la même revue, cinquante-quatre personnalités
 * différentes. Chaque entrée dit **comment cette semaine-là traite les sept
 * chapitres** : la matière, le motif qui revient d'un chapitre à l'autre, la
 * lumière, la palette, la scène de couverture, et **les sept sujets**, un par
 * chapitre.
 *
 * C'est ce tableau — et lui seul — qui produit :
 *
 * 1. **les briefs d'image** (`scripts/faire-prompt-aime.ts`) — une phrase par
 *    image, la même pour tout le monde ;
 * 2. **le manifeste** de la bibliothèque (`npm run visuels`) — semaine,
 *    chapitre, titre, univers, saison, style, sujet, couleur, description,
 *    mots-clés ;
 * 3. **les replis** : quand une image n'est pas encore livrée, la palette et le
 *    titre de la semaine tiennent la couverture, sans jamais emprunter le
 *    visuel d'une autre semaine.
 *
 * ## La règle de la maison
 *
 * Le mariage est **le territoire**, pas le sujet. Une robe parle du mariage,
 * une architecture parle du mariage, une table, une chanson, un objet transmis
 * en parlent aussi. On ne montre donc pas 54 fois des mariés : on montre
 * **54 mondes** qui mènent tous au mariage.
 */

export interface DirectionDuMagazine {
  /** 1 à 54. */
  numero: number;
  /** Le titre de la semaine, comme un titre de numéro : « Testament corse ». */
  titre: string;
  /** La famille visuelle : « Méditerranée insulaire, documentaire ». */
  style: string;
  /** L'ancrage : lieux, cultures, époques dont la semaine se réclame. */
  terroir: string;
  /** Les matières : ce qu'on doit pouvoir toucher du regard. */
  matiere: string;
  /** Le motif qui revient dans les sept chapitres — la cohérence de la semaine. */
  motif: string;
  /** La lumière de la semaine, dite comme on la décrit à un chef opérateur. */
  lumiere: string;
  /** Les deux couleurs de la semaine : le fond éditorial, et l'accent. */
  palette: { fond: string; accent: string };
  /** Ce que doit montrer la couverture — un monde, pas un mariage. */
  coverSujet: string;
  /** Les sept sujets, dans l'ordre des chapitres (01 → 07). */
  chapitres: string[];
}

