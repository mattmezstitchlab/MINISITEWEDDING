-- ----------------------------------------------------------------------------
--  Clés d’édition
--
--  Un jeton aléatoire par site, stocké sous forme d’empreinte SHA-256 : la
--  base ne contient jamais le secret en clair. Il est renvoyé une seule fois,
--  à la création (api/create-site.js), puis conservé par le navigateur.
--  Voir server/auth.js et la section « Sécurité » du README.
-- ----------------------------------------------------------------------------
-- Clés d’édition. Une ligne par site, créée en même temps que lui par
-- POST /api/create-site. `edit_token` ne contient QUE l’empreinte SHA-256 du
-- jeton : le clair n’est renvoyé qu’une fois, à la création, et n’est jamais
-- stocké côté serveur. Voir server/auth.js et la section « Exploitation ».
create table if not exists public.site_secrets (
  site_id    bigint primary key references public.wedding_sites (id) on delete cascade,
  edit_token text not null,           -- sha256(jeton) en hexadécimal, 64 caractères
  created_at timestamptz not null default now()
);

-- Bucket des images importées depuis l’éditeur (voir api/upload.js).
insert into storage.buckets (id, name, public)
values ('wedding-media', 'wedding-media', true)
on conflict (id) do nothing;

-- ============================================================================
--  Row Level Security
--
--  Les fonctions serverless utilisent la clé de service, qui contourne RLS :
--  activer RLS sans politique bloque uniquement les accès directs avec la clé
--  anonyme, ce qui est exactement ce que l’on veut — le navigateur ne parle
--  jamais à Supabase, seulement à /api/*.
--
--  L’éditeur est protégé par une clé (en-tête `x-site-token`, vérifiée côté
--  serveur dans server/auth.js) : n’ouvrez PAS RLS à des écritures anonymes,
--  cela court-circuiterait ce contrôle.
-- ============================================================================
do $$
declare
  t text;
begin
  foreach t in array array[
    'wedding_sites', 'site_sections', 'programme_events', 'infos_pratiques',
    'gallery_photos', 'faqs', 'rsvp_events', 'rsvp_responses', 'gift_options',
    'media_assets', 'site_secrets'
  ]
  loop
    execute format('alter table public.%I enable row level security', t);
  end loop;
end
$$;

