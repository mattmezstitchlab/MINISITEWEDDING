-- Un site de mariage : identité, date, lieu, apparence et contenus du hero.
create table if not exists public.wedding_sites (
  id              bigint generated by default as identity primary key,
  slug            text not null unique,
  partner1        text not null default '',
  partner2        text not null default '',
  wedding_date    date,
  venue           text not null default '',
  city            text not null default '',
  -- Apparence : identifiants des catalogues de src/lib/weddingStyles.ts
  style           text not null default 'editorial',
  phase           text not null default 'avant',        -- avant | pendant | apres
  typography      text not null default 'spatial',
  accent_color    text not null default '#16171A',
  button_style    text not null default 'pill',         -- pill | soft | square
  shape           text not null default 'soft',         -- soft | sharp | round
  layout          text not null default 'magazine',     -- minimal | magazine | immersif | galerie
  animation_level text not null default 'fluide',       -- calme | fluide | spectaculaire
  -- Contenus
  hero_photo      text not null default '',
  hero_title      text not null default '',
  hero_subtitle   text not null default '',
  story_title     text not null default '',
  story_text      text not null default '',
  story_photo     text not null default '',
  announcement    text not null default '',
  contact_email   text not null default '',
  contact_phone   text not null default '',
  published       boolean not null default false,
  created_at      timestamptz not null default now()
);

create index if not exists wedding_sites_slug_idx on public.wedding_sites (slug);

-- Ordre et visibilité des sections (clés lues par SECTION_COMPONENTS).
create table if not exists public.site_sections (
  id          bigint generated by default as identity primary key,
  site_id     bigint not null references public.wedding_sites (id) on delete cascade,
  section_key text not null,   -- hero | histoire | programme | lieux | infos | rsvp | cagnotte | galerie | faq | contact | footer
  title       text not null default '',
  visible     boolean not null default true,
  position    integer not null default 0
);

create index if not exists site_sections_site_idx on public.site_sections (site_id, position);

-- Déroulé du Jour J.
create table if not exists public.programme_events (
  id          bigint generated by default as identity primary key,
  site_id     bigint not null references public.wedding_sites (id) on delete cascade,
  event_time  text not null default '',
  title       text not null default '',
  description text not null default '',
  place       text not null default '',
  icon        text not null default 'clock',
  position    integer not null default 0
