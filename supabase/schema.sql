create index if not exists programme_events_site_idx on public.programme_events (site_id, position);

-- Informations pratiques (parking, hébergements, dress code, lieux…).
create table if not exists public.infos_pratiques (
  id          bigint generated by default as identity primary key,
  site_id     bigint not null references public.wedding_sites (id) on delete cascade,
  category    text not null default '',
  title       text not null default '',
  detail      text not null default '',
  event_time  text not null default '',
  link_label  text not null default '',
  position    integer not null default 0
