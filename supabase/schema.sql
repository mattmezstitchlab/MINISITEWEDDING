create index if not exists infos_pratiques_site_idx on public.infos_pratiques (site_id, position);

-- Galerie du site (les photos sont stockées dans le bucket `wedding-media`).
create table if not exists public.gallery_photos (
  id         bigint generated by default as identity primary key,
  site_id    bigint not null references public.wedding_sites (id) on delete cascade,
  url        text not null default '',
  caption    text not null default '',
  position   integer not null default 0,
  is_private boolean not null default false
);

create index if not exists gallery_photos_site_idx on public.gallery_photos (site_id, position);

create table if not exists public.faqs (
  id       bigint generated by default as identity primary key,
  site_id  bigint not null references public.wedding_sites (id) on delete cascade,
  question text not null default '',
  answer   text not null default '',
  position integer not null default 0
);

create index if not exists faqs_site_idx on public.faqs (site_id, position);

-- Moments proposés aux invités dans le formulaire RSVP.
create table if not exists public.rsvp_events (
  id          bigint generated by default as identity primary key,
  site_id     bigint not null references public.wedding_sites (id) on delete cascade,
  name        text not null default '',
  description text not null default '',
  position    integer not null default 0
